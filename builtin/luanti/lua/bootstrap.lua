local PALETTED_PARAMTYPE2 = {
	color = true, colorfacedir = true, color4dir = true,
	colorwallmounted = true, colordegrotate = true,
}

-- A box list flattened: six numbers a box, with a tag ahead of each when
-- one is asked for
local function flatten_boxes(boxes, out, tag)
	if type(boxes) ~= "table" then
		return
	end
	-- One box is six numbers; several is a list of those
	if type(boxes[1]) == "number" then
		boxes = {boxes}
	end
	for _, box in ipairs(boxes) do
		if type(box) == "table" and #box >= 6 then
			local ok = true
			for i = 1, 6 do
				if type(box[i]) ~= "number" then
					ok = false
				end
			end
			if ok then
				if tag then
					out[#out + 1] = tag
				end
				for i = 1, 6 do
					out[#out + 1] = box[i]
				end
			end
		end
	end
end

local function node_boxes(def)
	local nb = def and def.node_box
	if type(nb) ~= "table" or nb.type ~= "fixed" then
		return nil
	end
	local out = {}
	flatten_boxes(nb.fixed, out)
	if #out == 0 then
		return nil
	end
	return out
end

-- A "connected" node box, as the mesher's tagged quads: the fixed boxes
-- untagged, and each connect_* set tagged with the direction it needs a
-- neighbour in -- the same tag a fence's bars carry (1 +y, 2 -y, 3 +x, 4
-- -x, 5 +z, 6 -z; Luanti's front is -z and its left -x). Seven numbers a
-- box. simplified: the disconnected_* boxes, drawn where a side has
-- nothing, are left out; VoxeLibre's fences, panes and chorus have none.
local CONNECTED_TAGS = {connect_top = 1, connect_bottom = 2,
		connect_right = 3, connect_left = 4, connect_back = 5, connect_front = 6}

local function node_boxes_connected(def)
	local nb = def and def.node_box
	if type(nb) ~= "table" or nb.type ~= "connected" then
		return nil
	end
	local out = {}
	flatten_boxes(nb.fixed, out, 0)
	for key, tag in pairs(CONNECTED_TAGS) do
		flatten_boxes(nb[key], out, tag)
	end
	if #out == 0 then
		return nil
	end
	return out
end

-- What it connects to and what it is, for the mesher's connect groups:
-- the "group:x" entries of connects_to, and the node's own groups, each
-- list as one string
local function group_names(list)
	local out = {}
	for _, name in ipairs(list or {}) do
		local g = type(name) == "string" and name:match("^group:(.+)$")
		if g then
			out[#out + 1] = g
		end
	end
	return table.concat(out, ";")
end

local function own_group_names(def)
	local out = {}
	for g, v in pairs(def and def.groups or {}) do
		if (tonumber(v) or 0) > 0 then
			out[#out + 1] = g
		end
	end
	table.sort(out)
	return table.concat(out, ";")
end

-- How a node's texture alpha is meant to be used, which Luanti spells three
-- ways: "opaque" draws every texel, "clip" draws a texel or leaves it out
-- entirely, and "blend" draws it through. A node that says nothing takes the
-- default its drawtype has -- opaque for the five below and clip for
-- everything else, which is what makes a leaf a leaf without any mod saying
-- so -- and the deprecated boolean form means blend or clip where the
-- default is opaque and clip or opaque where it is not. See lua_api.md,
-- "use_texture_alpha".
local ALPHA_OPAQUE_BY_DEFAULT = {
	normal = true, liquid = true, flowingliquid = true,
	mesh = true, nodebox = true,
}

local function alpha_mode_of(def, drawtype)
	local default_opaque = ALPHA_OPAQUE_BY_DEFAULT[drawtype] or false
	local v = def and def.use_texture_alpha
	if v == nil or v == false then
		return default_opaque and "opaque" or "clip"
	end
	if v == true then
		return default_opaque and "blend" or "clip"
	end
	return v
end

-- The rule, checked where it is written: stone says nothing and is opaque, a
-- leaf and a plant say nothing and are cutouts, glass says what it wants,
-- and the deprecated boolean means blend where the default is opaque and
-- clip where it is not.
assert(alpha_mode_of(nil, "normal") == "opaque")
assert(alpha_mode_of({}, "nodebox") == "opaque")
assert(alpha_mode_of({}, "plantlike") == "clip")
assert(alpha_mode_of({}, "allfaces_optional") == "clip")
assert(alpha_mode_of({use_texture_alpha = "blend"}, "glasslike") == "blend")
assert(alpha_mode_of({use_texture_alpha = "opaque"}, "plantlike") == "opaque")
assert(alpha_mode_of({use_texture_alpha = true}, "normal") == "blend")
assert(alpha_mode_of({use_texture_alpha = true}, "plantlike") == "clip")
assert(alpha_mode_of({use_texture_alpha = false}, "normal") == "opaque")
assert(alpha_mode_of({use_texture_alpha = false}, "plantlike") == "clip")

-- What a node's surface is made of -- roughness, spec_strength,
-- bumpiness, translucency, spots, static_spots -- guessed the way
-- extensions/luanti_client guesses it, out of the same file, so the two
-- clients' atlases derive the same normal and spec maps. The extension
-- is at a fixed place beside this module. See [VOXEL_MATERIALS].
local surface = dofile(module_path ..
		"/../../extensions/luanti_client/surface.lua")
-- BUILDAT_LUANTI_NO_SPOTS=1 (the reference runs set it): no sparkle,
-- moving or standing, on any surface. The path-traced reference does
-- not render spots, so a comparison against it is cleaner without them
-- on the client either; the game's look is untouched otherwise.
local NO_SPOTS = (os.getenv and os.getenv("BUILDAT_LUANTI_NO_SPOTS") or "") ~= ""
local function surface_for(def)
	local out = surface.for_node(def)
	if NO_SPOTS then
		out.spots = 0
		out.static_spots = 0
	end
	return out
end

function core.__voxel_defs()
	local max_id = 0
	for id in pairs(core.__content_names) do
		if id > max_id then
			max_id = id
		end
	end
	local out = {}
	for id = 1, max_id do
		local name = core.__content_names[id]
		local def = name and core.registered_nodes[name] or nil
		local drawtype = def and def.drawtype or "normal"
		-- Whether light gets past this node, which in Luanti is a separate
		-- thing from whether it is drawn: glass has faces and lets the sun
		-- through. buildat used to have one test for both; see
		-- VoxelDefinition::transmits_light.
		local sunlight = (drawtype == "airlike") or
				(def and def.sunlight_propagates) or false
		local is_liquid = (drawtype == "liquid") or
				(drawtype == "flowingliquid")
		out[id] = {
			id = id,
			name = name or ("unknown_" .. id),
			drawtype = drawtype,
			sunlight = sunlight and true or false,
			-- Only airlike is nothing at all standing there; a glass pane
			-- that light passes through is still something
			empty = (drawtype == "airlike"),
			walkable = (def == nil) or (def.walkable ~= false),
			-- A ladder, a vine, a rope: what the client's physics holds on
			-- to instead of falling past it
			climbable = (def and def.climbable) and true or false,
			-- How much it holds a body back. Luanti's own rule: a node
			-- that says nothing takes liquid_viscosity, which is why water
			-- is thick without any game saying so.
			move_resistance = (def and (def.move_resistance or
					def.liquid_viscosity)) or 0,
			-- What the player is in: Luanti's liquid_move_physics, which
			-- defaults to "it is a liquid" and a game may set either way
			-- ([WATER_PARITY])
			swimmable = (def and def.liquid_move_physics ~= nil) and
					(def.liquid_move_physics and true or false) or is_liquid,
			-- What standing on it does to the player: the groups of the
			-- same names, read by the client's physics ([PLAYER_PHYSICS])
			bouncy = (def and def.groups and def.groups.bouncy) or 0,
			slippery = (def and def.groups and def.groups.slippery) or 0,
			disable_jump = (def and def.groups and
					(def.groups.disable_jump or 0) > 0) or false,
			disable_descend = (def and def.groups and
					(def.groups.disable_descend or 0) > 0) or false,
			light_source = (def and def.light_source) or 0,
			tiles = is_liquid and (liquid_tiles(def) or tile_names(def)) or
					tile_names(def),
			-- Which of those six are a strip of animation frames; the module
			-- cuts the first frame out of one before it goes in an atlas,
			-- because a whole strip stretched over a face is water's
			-- sixteen frames at once
			tile_frames = tile_frame_aspects(six_tile_defs(def, is_liquid)),
			node_box = (drawtype == "nodebox") and node_boxes(def) or nil,
			node_box_connected = (drawtype == "nodebox") and
					node_boxes_connected(def) or nil,
			node_box_connects = (drawtype == "nodebox") and
					group_names(def and def.connects_to) or nil,
			node_box_groups = (drawtype == "nodebox") and
					own_group_names(def) or nil,
			visual_scale = (def and def.visual_scale) or 1.0,
			-- What says two liquid nodes are the same liquid: a water source
			-- and a flowing water both name the source. Luanti pairs them
			-- this way and so does the mesher's shape_group.
			liquid_group = is_liquid and
					((def and def.liquid_alternative_source) or name) or nil,
			-- How many of the eight levels this liquid actually spends; a
			-- shorter range puts them all at the top of the voxel
			liquid_range = (def and def.liquid_range) or 8,
			-- A rooted plant's plant, which is special_tiles[1]: the node's
			-- own tiles are the cube it is rooted in
			overlay_tile = (drawtype == "plantlike_rooted") and
					tile_name_of((def and def.special_tiles or {})[1]) or nil,
			-- Blended rather than alpha masked. Without it framed glass and
			-- panes are drawn with every texel either solid or gone, where
			-- the game meant them to be seen through.
			alpha_blend = alpha_mode_of(def, drawtype) == "blend",
			surface = surface_for(def and {
				name = name, drawtype = drawtype, groups = def.groups,
				waving = def.waving, light_source = def.light_source,
				blend = alpha_mode_of(def, drawtype) == "blend",
			} or nil),
			-- Cut out by the texture's own alpha, which is what a leaf, a
			-- plant, a rail and a ladder are. Without it the holes in the
			-- picture are drawn in whatever is under the alpha, which is
			-- black.
			alpha_clip = alpha_mode_of(def, drawtype) == "clip",
			-- The model a "mesh" node is made of; the module reads it and
			-- the quads become the node's shape
			mesh = (drawtype == "mesh") and def and def.mesh or nil,
			facing = def and FACING_OF_PARAMTYPE2[def.paramtype2] or nil,
			-- The palette its param2 picks a colour from, if it has one:
			-- the module reads the image and gives each colour a variant
			palette = (def and def.palette and
					PALETTED_PARAMTYPE2[def.paramtype2]) and def.palette or nil,
			-- Which rails this one reaches: Luanti's connect_to_raillike,
			-- an id from core.raillike_group(). Rails of the same id join.
			raillike_group = (drawtype == "raillike") and
					((def and def.connect_to_raillike) or 0) or nil,
		}
	end
	return out
end

