	return day_count
end

-- One Luanti step. The module calls this at Luanti's own rate rather than
-- buildat's, because a mod's globalstep dtime and core.after's resolution are
-- written against dedicated_server_step.
-- The globalsteps a mod registered, run once per Luanti step.
--
-- core.after is one of them: the vendored builtin/common/after.lua keeps its
-- queue in a globalstep of its own, so this is what makes core.after fire at
-- all -- and what every mod that does anything on a timer is written around.
--
-- A callback that errors is logged and the rest still run, where Luanti
-- stops the server. One mod's bad frame should not stop the clock or the
-- other mods here: the module already treats a failed step as a warning
-- rather than the end, and this is the same posture one level down.
local function run_globalsteps(dtime)
	local callbacks = core.registered_globalsteps
	if callbacks == nil then
		return
	end
	for i = 1, #callbacks do
		local callback = callbacks[i]
		local origin = core.callback_origins and core.callback_origins[callback]
		if origin then
			core.set_last_run_mod(origin.mod)
		end
		local ok, err = pcall(callback, dtime)
		if not ok then
			core.log("error", "globalstep: " .. tostring(err))
		end
	end
end

--
-- ABMs
--
-- An ABM is a rule that runs on every node of a kind, forever: grass turns
-- to dirt under something, a furnace burns, a leaf decays. Luanti runs them
-- over the blocks that are active -- near a player -- and so does this:
-- __active_boxes() is the loaded sections within a section of a player,
-- which is Luanti's own active_block_range of four blocks. A world with
-- nobody in it is a world where nothing happens, there as well as here.
--
-- The registry freezes after the mods have loaded, so the timers are built
-- on the first step rather than kept up to date with it.
--
-- The match is on content ids and happens in the module, so what crosses
-- into Lua is the voxels a rule is about and not the section.
--
-- simplified: no time budget and no catch-up, and every active section is
-- read for every rule that is due. Luanti spends at most a share of a step
-- on ABMs, skips ahead when a block comes back after a long time away, and
-- keeps a per-block list of which node kinds are in it so that most blocks
-- are never read. The active range is what keeps the cost bounded by the
-- players instead of by the world; the other three are still upgrades.

local abm_timers = nil
local abm_ids = nil
-- The same for the LBMs; see run_lbms()
local lbm_ids = nil
-- Which cells have had their LBMs, by the cell's own corner; see
-- active_cells()
local lbm_done = {}

-- What a sweep does before it looks at the clock again. Luanti runs an LBM
-- on a map block, which is 16 voxels; an active box here is a section,
-- which is 64, and a section's worth in one go was five seconds for the
-- LBMs and two and a half for the ABMs -- and a budget cannot stop work
-- that has already started. 32 is what the map is in chunks of.
local SWEEP_CELL = 32

-- Every active box, in pieces no bigger than SWEEP_CELL on a side. A box
-- that is already that small or smaller comes through as itself.
local function active_cells()
	local out = {}
	for _, box in ipairs(core.__active_boxes_now()) do
		local z = box[3]
		while z <= box[6] do
			local ez = math.min(z + SWEEP_CELL - 1, box[6])
			local y = box[2]
			while y <= box[5] do
				local ey = math.min(y + SWEEP_CELL - 1, box[5])
				local x = box[1]
				while x <= box[4] do
					local ex = math.min(x + SWEEP_CELL - 1, box[4])
					out[#out + 1] = {x, y, z, ex, ey, ez}
					x = ex + 1
				end
				y = ey + 1
			end
			z = ez + 1
		end
	end
	return out
end

-- What a node registered after load invalidates: which ids a name list is
-- about. Called by core.__forget_name_ids() above.
function core.__forget_sweep_ids()
	abm_timers = nil
	abm_ids = nil
	lbm_ids = nil
	-- A node registered late can match an LBM that a section was already
	-- swept for, so those sections are owed another pass
	lbm_done = {}
end

-- The active range, asked for once a step: the loaded sections within a
-- section of a player. Everything that runs where the map is -- an ABM, a
-- node timer, an entity -- asks the same list, because they are active for
-- the same reason and stop for the same one.
local active_boxes_cache = nil

-- The loaded sections, once a step: the world streams between steps and not
-- during one, so every answer inside a step agrees with every other -- which
-- is what a mod comparing two of them relies on.
local loaded_boxes_cache = nil

local function loaded_boxes_now()
	if loaded_boxes_cache == nil then
		loaded_boxes_cache = __luanti_loaded_boxes and __luanti_loaded_boxes()
				or {}
	end
	return loaded_boxes_cache
end

-- The map check's switch: with nobody in the world nothing is active, and
-- the check runs a game's rules over the map it just wrote, so while it
-- runs every loaded section is (lua/check_map.lua)
core.__active_everywhere = false

function core.__active_boxes_now()
	if active_boxes_cache == nil then
		active_boxes_cache = core.__active_everywhere and loaded_boxes_now()
				or __active_boxes()
	end
	return active_boxes_cache
end

-- The mapblocks a set of voxel boxes covers, as the vectors Luanti hands
-- back: a section is four blocks across in each direction, so one box is
-- sixty-four of them.
local function blocks_in_boxes(boxes)
	local out = {}
	local seen = {}
	for i = 1, #boxes do
		local b = boxes[i]
		for bx = math.floor(b[1] / 16), math.floor(b[4] / 16) do
		for by = math.floor(b[2] / 16), math.floor(b[5] / 16) do
		for bz = math.floor(b[3] / 16), math.floor(b[6] / 16) do
			local h = core.hash_node_position({x = bx, y = by, z = bz})
			if seen[h] == nil then
				seen[h] = true
				out[#out + 1] = vector.new(bx, by, bz)
			end
		end
		end
		end
	end
	return out
end

-- Which blocks are there, which of them are stepping, and which could be
-- loaded but are not.
--
-- simplified: nothing here indexes what the save holds but has not loaded,
-- so the third is always empty. Luanti's answers what its map database has
-- on disk, which a mod uses to walk a world without generating it.
core.__forget_loaded_boxes = function()
	loaded_boxes_cache = nil
end

function core.get_loaded_blocks()
	return blocks_in_boxes(loaded_boxes_now())
end

-- Out of the loaded ones rather than out of the active boxes themselves, so
-- that the answer is a subset of get_loaded_blocks() whatever has streamed
-- in or out between the two calls -- which is what a mod comparing them
-- expects and what the active box cache, being a step old, cannot promise.
function core.get_active_blocks()
	local out = {}
	for _, b in ipairs(core.get_loaded_blocks()) do
		if core.__is_active({x = b.x * 16 + 8, y = b.y * 16 + 8,
				z = b.z * 16 + 8}) then
			out[#out + 1] = b
		end
	end
	return out
end

function core.get_loadable_blocks()
	return {}
end

-- Whether the block at a position is at least as far along as the status
-- named: Luanti's own order is unknown, emerging, loaded, active. Nothing
-- here is ever "emerging" as a status of its own -- a section is loaded or
-- it is not -- so that rung is empty and a block asked about while its
-- section streams answers "unknown".
local BLOCK_STATUS_RANK = {unknown = 0, emerging = 1, loaded = 2, active = 3}

function core.compare_block_status(pos, condition)
	local want = BLOCK_STATUS_RANK[condition]
	if want == nil then
		return nil
	end
	local x, y, z = to_pos(pos)
	local p = {x = x, y = y, z = z}
	local rank = 0
	if core.__is_active(p) then
		rank = 3
	else
		local boxes = loaded_boxes_now()
		for i = 1, #boxes do
			local b = boxes[i]
			if x >= b[1] and y >= b[2] and z >= b[3] and
					x <= b[4] and y <= b[5] and z <= b[6] then
				rank = 2
				break
			end
		end
	end
	return rank >= want
end

function core.__is_active(pos)
	local boxes = core.__active_boxes_now()
	for i = 1, #boxes do
		local b = boxes[i]
		if pos.x >= b[1] and pos.y >= b[2] and pos.z >= b[3] and
				pos.x <= b[4] and pos.y <= b[5] and pos.z <= b[6] then
			return true
		end
	end
	return false
end

-- Which content ids a rule is about, since the sweep matches ids and not
-- names: a name list is turned into one of these once, because the node
-- registry is frozen by the time anything steps.
local function ids_matching(nodenames)
	local matches = name_matcher(nodenames)
	local ids = {}
	for name, _ in pairs(core.registered_nodes) do
		if matches(name) then
			ids[#ids + 1] = core.get_content_id(name)
		end
	end
	return ids
end

local function abm_neighbors_ok(abm, pos)
	if abm.neighbors == nil or #abm.neighbors == 0 then
		return true
	end
	return core.find_node_near(pos, 1, abm.neighbors) ~= nil
end

-- Every active section, once, against a set of ids per rule: on_hits(k,
-- hits) gets the flat x,y,z list of what the section held of set k. One read
-- per section however many rules there are, because the read is what a sweep
-- costs and the module matches 32 sets of ids at a time.
local function sweep_one_box(box, id_sets, on_hits)
	for first = 1, #id_sets, 32 do
		local last = math.min(first + 31, #id_sets)
		local batch = {}
		for k = first, last do
			batch[#batch + 1] = id_sets[k]
		end
		local found = __find_ids(box[1], box[2], box[3],
				box[4], box[5], box[6], batch)
		for k = first, last do
			on_hits(k, found[k - first + 1])
		end
	end
end

local function sweep_sections(id_sets, on_hits)
	if #id_sets == 0 then
		return 0
	end
	local boxes = core.__active_boxes_now()
	for _, box in ipairs(boxes) do
		sweep_one_box(box, id_sets, on_hits)
	end
	return #boxes
end

-- One rule over the voxels of its kind that one section turned out to hold
-- Runs the rule over its hits from `from` and returns where it stopped:
-- nil for the end, or the index to carry on from when the deadline
-- passed. Looked at every 64 hits, since a hit is a get_node and a
-- mod's action, microseconds to milliseconds.
local function run_abm(abm, hits, from, until_us)
	local chance = abm.chance or 1
	local min_y = abm.min_y or -32768
	local max_y = abm.max_y or 32767
	for i = from or 1, #hits, 3 do
		if i % 192 == 1 and i > 1 and until_us and
				core.get_us_time() >= until_us then
			return i
		end
		local y = hits[i + 1]
		if y >= min_y and y <= max_y and
				(chance <= 1 or math.random(chance) == 1) then
			local pos = {x = hits[i], y = y, z = hits[i + 2]}
			if abm_neighbors_ok(abm, pos) then
				core.set_last_run_mod(abm.mod_origin)
				-- The two counts are how many objects are in the block and
				-- around it; there are none yet
				local ok, err = pcall(abm.action, pos, core.get_node(pos),
						0, 0)
				if not ok then
					core.log("error", "abm " .. tostring(abm.label or "?") ..
							": " .. tostring(err))
				end
			end
		end
	end
end

-- How long a step may spend sweeping before it puts the rest down and picks
-- it up on the next one. VoxeLibre's rules over ten active sections were
-- measured at one to ten seconds a sweep, and a step of ten seconds is ten
-- seconds of everything else waiting -- the player's own click among it,
-- which is what a playtest of it felt as the game being broken. Luanti
-- spends a share of its own step on ABMs for the same reason.
--
-- The sweep is put down inside a batch as well: the hits of the batch are
-- kept on the sweep with the rule and the hit it got to, so a section
-- whose rules are slow overshoots by 64 hits of one rule and not by the
-- section. Before that one box's batch was 3.5 s of a step in VoxeLibre
-- (the fuzz run, 2026-09-17), with the budget looked at only after it.
-- 0.1 (2026-09-18), down from 0.2: the step's ceiling is 0.25 s and the
-- ABMs are not the only thing in it
local ABM_BUDGET_S = 0.1

-- Where a sweep that ran out of budget got to: which rules it is for, the
-- sections it was going to read, and how far along it is. A rule that comes
-- due while one is running stays due rather than joining it, so no rule is
-- swept twice and none is forgotten.
local abm_sweep = nil

local function run_abms(dtime)
	local abms = core.registered_abms
	if abms == nil or #abms == 0 then
		return
	end
	if abm_timers == nil then
		abm_timers = {}
		abm_ids = {}
		for i = 1, #abms do
			abm_timers[i] = 0
			abm_ids[i] = ids_matching(abms[i].nodenames)
		end
	end
	local due = nil
	for i = 1, #abms do
		abm_timers[i] = abm_timers[i] + dtime
		if abm_timers[i] >= (abms[i].interval or 1) then
			if abm_sweep ~= nil then
				-- Held at the interval, so that it is due again the moment
				-- the sweep that is running has finished
				abm_timers[i] = abms[i].interval or 1
			else
				abm_timers[i] = 0
				due = due or {}
				due[#due + 1] = i
			end
		end
	end
	if abm_sweep == nil then
		if due == nil then
			return
		end
		local sets = {}
		for k = 1, #due do
			sets[k] = abm_ids[due[k]]
		end
		-- Cells and not whole sections, for the same reason the LBM sweep
		-- takes them: the budget below is looked at between boxes, so one
		-- box is the smallest thing it can stop after.
		abm_sweep = {due = due, sets = sets,
				boxes = active_cells(), box_i = 1, first = 1}
	end
	local sweep = abm_sweep
	local until_us = core.get_us_time() + ABM_BUDGET_S * 1000000
	while sweep.box_i <= #sweep.boxes do
		local box = sweep.boxes[sweep.box_i]
		local last = math.min(sweep.first + 31, #sweep.sets)
		local batch = {}
		for k = sweep.first, last do
			batch[#batch + 1] = sweep.sets[k]
		end
		-- The batch's hits, read once and kept while the deadline
		-- interrupts the rules over them
		if sweep.found == nil then
			sweep.found = __find_ids(box[1], box[2], box[3], box[4], box[5],
					box[6], batch)
			sweep.k = sweep.first
			sweep.at = nil
		end
		while sweep.k <= last do
			local stopped = run_abm(abms[sweep.due[sweep.k]],
					sweep.found[sweep.k - sweep.first + 1], sweep.at, until_us)
			if stopped then
				sweep.at = stopped
				return
			end
			sweep.at = nil
			sweep.k = sweep.k + 1
			if core.get_us_time() >= until_us then
				if sweep.k > last then
					break
				end
				return
			end
		end
		sweep.found = nil
		sweep.first = last + 1
		if sweep.first > #sweep.sets then
			sweep.first = 1
			sweep.box_i = sweep.box_i + 1
		end
		if core.get_us_time() >= until_us then
			return
		end
	end
	abm_sweep = nil
end

--
-- LBMs
--
-- The same idea on a section rather than on a timer: a rule that runs over
-- the nodes of a kind when the part of the map they are in is loaded, which
-- is how a game fixes up what it saved before it changed its mind about it.
--
-- simplified: a section is swept the first time it is seen active and not
-- again, so run_at_every_load has nothing to be different about for a world
-- this module generated itself. What is kept is only which sections have
-- been swept this run; a section that unloads and comes back is swept again.
--
-- **An imported world is the case where that is not good enough**, and it is
-- handled. Luanti records the game time each LBM was introduced at and runs
-- one only on mapblocks older than that, so an LBM a world already knows
-- about never runs on it again. Sweeping regardless meant running every
-- fix-up a game has ever written against a world that has already had it:
-- VoxeLibre's fix_grass_palette_indexes re-derives every grass block's
-- palette index from the *current* version's biome code, and the reference
-- world was generated five minor versions earlier, so it repainted the
-- world's grass a different green. That read as a rendering fault for two
-- days. See [GREEN_BIAS] in doc/plan/rendering_plan.md.
--
-- The list comes from the imported world's env_meta.txt and is kept in the
-- save; see lbm_names_of() in luanti.cpp.
local function lbms_the_world_has_had()
	local out = {}
	local field = __luanti_lbm_introduced
	if type(field) ~= "string" then
		return out
	end
	for name in field:gmatch("([^;]+)") do
		out[name] = true
	end
	return out
end


-- Runs the rule over its hits from `from` and returns where it stopped:
-- nil for the end, or the position index to carry on from when the
-- deadline passed -- looked at every 64 positions, the way run_abm()
-- does. A bulk_action is one call and runs whole.
local function run_lbm(lbm, hits, from, until_us)
	local positions = {}
	for i = 1, #hits, 3 do
		positions[#positions + 1] =
				{x = hits[i], y = hits[i + 1], z = hits[i + 2]}
	end
	if #positions == 0 then
		return nil
	end
	core.set_last_run_mod(lbm.mod_origin)
	-- dtime_s is how long the block was away, and nothing here has been
	local ok, err
	if lbm.bulk_action then
		ok, err = pcall(lbm.bulk_action, positions, 0)
	else
		ok = true
		for i = from or 1, #positions do
			if i % 64 == 0 and until_us and core.get_us_time() >= until_us then
				return i
			end
			local pos = positions[i]
			local ok1, err1 = pcall(lbm.action, pos, core.get_node(pos), 0)
			if not ok1 then
				ok, err = false, err1
				break
			end
		end
	end
	if not ok then
		core.log("error", "lbm " .. tostring(lbm.name or "?") .. ": " ..
				tostring(err))
	end
	return nil
end

-- A cell's rules put down when the step's budget ran out, picked up
-- next step: the rule index, its hits and the position it got to. One
-- cell's LBMs were 0.18 s of a step in VoxeLibre with the budget looked
-- at only between cells ([STEP_PEAK]).
local lbm_pending = nil

-- Returns whether this was the load: the first steps happen before the world
-- has a section in it -- lua/check_map.lua steps the clock a whole day
-- before anything is flushed -- and a sweep over nothing is not one.
local function run_lbms()
	local lbms = core.registered_lbms
	if lbms == nil or #lbms == 0 then
		return true
	end
	-- Worked out once and kept, the way run_abms() keeps its own: turning a
	-- name list into ids walks every node the game registered -- two and a
	-- half thousand in VoxeLibre -- and this runs on every step that has
	-- sections to sweep. It was a quarter of all the Lua a VoxeLibre world
	-- spent generating, in name_matcher()'s inner function, and the whole of
	-- it was this rebuilding the same answer. core.__forget_name_ids()
	-- drops it, which is what a mod registering a node after load needs.
	if lbm_ids == nil then
		local had = lbms_the_world_has_had()
		lbm_ids = {}
		for i = 1, #lbms do
			-- No ids is no matches, which is how an LBM this world has
			-- already had costs nothing per section rather than being
			-- checked again in the sweep
			if had[lbms[i].name] and not lbms[i].run_at_every_load then
				lbm_ids[i] = {}
				core.log("info", "lbm " .. tostring(lbms[i].name) ..
						": this world has had it; not run again")
			else
				lbm_ids[i] = ids_matching(lbms[i].nodenames)
			end
		end
	end
	-- A cell at a time, and only the ones that have not had them, with a
	-- budget on how long one step may spend. Luanti runs an LBM on a block
	-- when that block loads; this used to sweep every active section in one
	-- go, and on a VoxeLibre world that was **46 seconds in one step** --
	-- the module's thread does one thing at a time, so that is 46 seconds
	-- of a server that answers nothing, a player's click and a shutdown
	-- among it. Measured with the step watchdog in builtin/luanti.
	--
	-- Cells that appear later get their LBMs too now, which they did not
	-- when this latched after one pass. What is not kept is which LBM ran
	-- where across a restart, the way Luanti's own lbm_meta is: a cell
	-- that unloads and comes back is swept again.
	local budget_us = 20000
	local t0 = core.get_us_time()
	local until_us = t0 + budget_us
	local swept = 0
	-- What was put down last step first, and within the budget
	if lbm_pending then
		while #lbm_pending > 0 do
			local job = lbm_pending[1]
			local stopped = run_lbm(lbms[job.k], job.hits, job.at, until_us)
			if stopped then
				job.at = stopped
				return true
			end
			table.remove(lbm_pending, 1)
		end
		lbm_pending = nil
		swept = 1
	end
	for _, cell in ipairs(active_cells()) do
		local key = cell[1] .. "," .. cell[2] .. "," .. cell[3]
		if not lbm_done[key] then
			if swept > 0 and core.get_us_time() > until_us then
				break
			end
			lbm_done[key] = true
			swept = swept + 1
			-- The cell's hits are read whole and its rules run until the
			-- deadline; what is left is kept for the next step
			local jobs = {}
			sweep_one_box(cell, lbm_ids, function(k, hits)
				if #hits > 0 then
					jobs[#jobs + 1] = {k = k, hits = hits, at = nil}
				end
			end)
			while #jobs > 0 do
				local job = jobs[1]
				local stopped = run_lbm(lbms[job.k], job.hits, job.at, until_us)
				if stopped then
					job.at = stopped
					lbm_pending = jobs
					return true
				end
				table.remove(jobs, 1)
			end
		end
	end
	return swept > 0
end

-- A step over this is logged with where it went: the module's thread
-- handles one thing at a time, so a step of seconds is seconds of
-- everything else waiting -- a player's click among it. The eight clock
-- reads a step costs for this are nothing beside what they measure. See
-- [STEP_PEAK] in doc/plan/performance_plan.md: every instance at trace,
-- the worst since the last line at info at most every LOG_EVERY_S.
local SLOW_STEP_S = 0.25
local LOG_EVERY_S = 5.0
local slow_said_at = nil
local slow_worst, slow_worst_phase = 0, ""

-- The longest step's wall time, held and decayed the way Luanti's own
-- max_lag is: the peak is what the last while was like, not what the
-- last step was. Multiplied by DECAY every DECAY_EVERY_S, which halves it
-- per 12 s -- a fifth of Luanti's minute, the user's pick ([STATUS_MS]);
-- with the phase that set it. And the latest step beside it for the row.
local DECAY, DECAY_EVERY_S = 0.9715, 0.5
local step_peak, step_peak_phase = 0, ""
local step_latest = 0
-- The worst step since somebody last asked, undecayed: the fixture's
-- count of seconds over the ceiling read the decaying peak and counted
-- one 0.45 s step eighty times ([STEP_SLICE], seed 5's rerun)
local step_worst, step_worst_phase = 0, ""
local decay_due = 0
local peak_told, latest_told, told_at = -1, -1, 0

-- get_server_step_peak() -> seconds, phase, latest step's seconds.
-- Luanti's get_server_max_lag() is the first number under its own name.
function core.get_server_step_peak()
	return step_peak, step_peak_phase, step_latest
end

-- get_server_step_worst() -> seconds, phase: the worst step since the
-- last call, and the call starts the next window
function core.get_server_step_worst()
	local s, p = step_worst, step_worst_phase
	step_worst, step_worst_phase = 0, ""
	return s, p
end

-- Work that runs on the server's thread outside core.__step() -- a
-- section's on_generated callbacks -- counts against the peak the same
-- way, since a client waits on it the same way
function core.__note_phase(phase, seconds)
	if seconds > step_peak then
		step_peak, step_peak_phase = seconds, phase
	end
	if seconds > step_worst then
		step_worst, step_worst_phase = seconds, phase
	end
	if seconds >= SLOW_STEP_S then
		core.log("trace", string.format("%s took %.2f s between steps",
				phase, seconds))
		if seconds > slow_worst then
			slow_worst, slow_worst_phase = seconds, phase
		end
	end
end
function core.get_server_max_lag()
	return step_peak
end

function core.__step(dtime)
	local t0 = core.get_us_time()
	local at = t0
	local parts = {}
	local function mark(name)
		local now = core.get_us_time()
		parts[#parts + 1] = {name, (now - at) / 1000000}
		at = now
	end
	-- The map moves between steps and not during one
	active_boxes_cache = nil
	core.__forget_loaded_boxes()
	run_globalsteps(dtime)
	mark("globalsteps")
	core.__step_objects(dtime)
	mark("objects")
	step_emerge(dtime)
	mark("emerge")
	run_node_timers(dtime)
	mark("timers")
	run_mapblocks_changed()
	mark("changed")
	-- Every step, not once: a section that appears later has had no LBMs,
	-- and run_lbms() is a table lookup per active section when there is
	-- nothing new
	run_lbms()
	mark("lbms")
	run_abms(dtime)
	mark("abms")
	local total = (core.get_us_time() - t0) / 1000000
	local longest, longest_phase = 0, ""
	for _, part in ipairs(parts) do
		if part[2] > longest then
			longest, longest_phase = part[2], part[1]
		end
	end
	-- The peak: decayed on its clock, raised by this step if it is worse
	decay_due = decay_due - dtime
	if decay_due <= 0 then
		step_peak = step_peak * DECAY
		decay_due = DECAY_EVERY_S
	end
	step_latest = total
	if total > step_peak then
		step_peak, step_peak_phase = total, longest_phase
	end
	if total > step_worst then
		step_worst, step_worst_phase = total, longest_phase
	end
	-- Told to the clients when the row would show a different number:
	-- the peak's millisecond, the latest's 10 ms bucket -- that one at
	-- most four times a second, so the row is live without a packet per
	-- step
	local shown = math.floor(step_peak * 1000)
	local bucket = math.floor(total * 100)
	local now = core.get_us_time()
	if shown ~= peak_told or
			(bucket ~= latest_told and now - told_at >= 250000) then
		peak_told, latest_told, told_at = shown, bucket, now
		__luanti_step_peak(step_peak, step_peak_phase)
	end
	if total >= SLOW_STEP_S then
		local said = {}
		for _, part in ipairs(parts) do
			if part[2] >= 0.05 then
				said[#said + 1] = string.format("%s %.2f s", part[1], part[2])
			end
		end
		local d = emerge_detail
		core.log("trace", string.format(
				"a step took %.2f s: %s (emerge: %d asked in %.2f s, " ..
				"%d callbacks in %.2f s, worst %.2f s by %s)", total,
				table.concat(said, ", "), d.asked, d.ids / 1000000,
				d.n_callbacks, d.callbacks / 1000000, d.worst / 1000000,
				d.worst_mod))
		if total > slow_worst then
			slow_worst, slow_worst_phase = total, longest_phase
		end
		local now = t0 / 1000000
		if slow_said_at == nil or now - slow_said_at >= LOG_EVERY_S then
			core.log("info", string.format(
					"a step took %.2f s, %s; the worst since the last line",
					slow_worst, slow_worst_phase))
			slow_said_at = now
			slow_worst, slow_worst_phase = 0, ""
		end
	end
	emerge_detail.ids, emerge_detail.asked = 0, 0
	emerge_detail.callbacks, emerge_detail.n_callbacks = 0, 0
	emerge_detail.worst, emerge_detail.worst_mod = 0, ""
	game_time = game_time + dtime
	local speed = tonumber(core.settings:get("time_speed")) or 72
	local day_seconds = 24 * 60 * 60
	time_of_day = time_of_day + dtime * speed / day_seconds
	while time_of_day >= 1.0 do
		time_of_day = time_of_day - 1.0
		day_count = day_count + 1
	end
end

-- What the module reads out of the clock and puts back into it. Three numbers
-- rather than a table, because that is all the clock is.
-- What a player is allowed to do. Luanti's server asks the auth handler and
-- hands back what it holds; the handler is the vendored builtin's own, and
-- it is the one that adds the singleplayer's extras and the admin's. A name
-- with no entry has no privileges, which is what Luanti answers too.
--
-- Somebody playing their own world can do anything in it, which is what
-- Luanti's own singleplayer means by the term -- its server hands out every
-- privilege there, rather than the give_to_singleplayer ones, which is why
-- /time works in singleplayer and not on a server. See is_singleplayer().
function core.get_player_privs(name)
	if core.is_singleplayer() then
		local all = {}
		for priv, _ in pairs(core.registered_privileges or {}) do
			all[priv] = true
		end
		return all
	end
	local handler = core.get_auth_handler and core.get_auth_handler()
	local entry = handler and handler.get_auth and handler.get_auth(name)
	return (entry and entry.privileges) or {}
end

-- What the module sends the clients every few seconds; they carry the clock
-- on themselves in between, which is what keeps the sky moving smoothly
function core.__send_time()
	if __luanti_send_time then
		__luanti_send_time(time_of_day,
				tonumber(core.settings:get("time_speed")) or 72)
	end
end

function core.__get_clock()
	return time_of_day, game_time, day_count
end

function core.__set_clock(tod, gt, dc)
	time_of_day = tod % 1.0
	game_time = gt
	day_count = dc
end

