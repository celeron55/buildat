	for id, name in pairs(core.__content_names) do
		local def = core.registered_nodes[name]
		if def then
			local liquid = 0
			if def.liquidtype == "flowing" then
				liquid = 1
			elseif def.liquidtype == "source" then
				liquid = 2
			end
			out[#out + 1] = id
			out[#out + 1] = (def.walkable ~= false) and 1 or 0
